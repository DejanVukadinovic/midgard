#!/usr/bin/env bash
# Run the full demo stack WITHOUT Docker (processes on localhost) against an existing PostgreSQL.
#   scripts/dev-local.sh up | down | restart-core | env
# Requires: cargo, go, curl, jq, psql, and PG_ADMIN_URL (superuser connection, default below).
# State (pids, logs, generated dev passwords) lives in the git-ignored .local/ directory.
source "$(dirname "$0")/lib.sh"
need cargo go curl jq psql

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LOCAL="$ROOT/.local"
mkdir -p "$LOCAL"
: "${PG_ADMIN_URL:=postgres://midgard:midgard@localhost:5432/postgres}"
PG_HOSTPORT="$(sed -E 's#^postgres://[^@]*@([^/]*)/.*#\1#' <<<"$PG_ADMIN_URL")"
PGUSER="$(sed -E 's#^postgres://([^:@]*).*#\1#' <<<"$PG_ADMIN_URL")"
PGPASSWORD="$(sed -E 's#^postgres://[^:]*:([^@]*)@.*#\1#' <<<"$PG_ADMIN_URL")"
export PGHOST="${PG_HOSTPORT%%:*}" PGPORT="${PG_HOSTPORT##*:}" PGUSER PGPASSWORD

PORT_CORE=${PORT_CORE:-8080} PORT_IDP=${PORT_IDP:-9000} PORT_CAP=${PORT_CAP:-8082}
# v0.2 fixture (WITH_V02=1): NATS JetStream + the language-independent echo provider.
PORT_NATS=${PORT_NATS:-4222} PORT_ECHO=${PORT_ECHO:-8083} NATS_SERVER_BIN=${NATS_SERVER_BIN:-nats-server}
BIN="$ROOT/target/debug"
# IDP=zitadel runs a real ZITADEL (binary from ZITADEL_BIN) instead of the offline dev IdP.
IDP=${IDP:-dev} ZITADEL_BIN=${ZITADEL_BIN:-zitadel} PORT_ZITADEL=${PORT_ZITADEL:-8085}
export IDP_DIR="$LOCAL/idp"

gen() { openssl rand -hex 16 2>/dev/null || head -c16 /dev/urandom | od -An -tx1 | tr -d ' \n'; }
load_env() {
  if [[ ! -f "$LOCAL/env" ]]; then
    umask 077
    {
      echo "MIDGARD_OWNER_PASSWORD=$(gen)"; echo "MIDGARD_APP_PASSWORD=$(gen)"
      echo "CAPABILITY_OWNER_PASSWORD=$(gen)"; echo "CAPABILITY_APP_PASSWORD=$(gen)"
    } >"$LOCAL/env"
  fi
  if ! grep -q '^ZITADEL_DB_PASSWORD=' "$LOCAL/env"; then
    umask 077
    { echo "ZITADEL_DB_PASSWORD=$(gen)"; echo "ZITADEL_MASTERKEY=$(gen | head -c 32)"; } >>"$LOCAL/env"
  fi
  if ! grep -q '^NATS_ADMIN_PASSWORD=' "$LOCAL/env"; then
    umask 077
    { echo "NATS_ADMIN_PASSWORD=pw$(gen)"; echo "NATS_PROVIDER_PASSWORD=pw$(gen)"; echo "NATS_CLIENT_PASSWORD=pw$(gen)"; } >>"$LOCAL/env"
  fi
  set -a; source "$LOCAL/env"; set +a
}

start() { # start <name> <command...>   (env inherited)
  local name="$1"; shift
  "$@" >"$LOCAL/$name.log" 2>&1 &
  echo $! >"$LOCAL/$name.pid"
}
stop() {
  local f="$LOCAL/$1.pid"
  if [[ -f "$f" ]]; then kill "$(cat "$f")" 2>/dev/null || true; rm -f "$f"; fi
}

# Identity-provider facts used by the services below. dev-idp: fixed fixtures. ZITADEL: generated by
# scripts/zitadel-bootstrap.sh into $IDP_DIR (project ids as audiences, user ids as subjects).
idp_vars() {
  if [[ "$IDP" == zitadel ]]; then
    set -a; source "$IDP_DIR/idp.env"; source "$IDP_DIR/secrets.env"; set +a
    export PLATFORM_ACCEPT_JWT_TYP=true CAPABILITY_ACCEPT_JWT_TYP=true   # ZITADEL JWT access tokens have typ JWT
    ISSUER="$IDP_ISSUER"; OP_SUBJECTS="$PLATFORM_OPERATOR_SUBJECTS"; PUB_SUBJECTS="$PLATFORM_PUBLISHER_SUBJECTS"
    DEPLOYER_CLIENT=example-deployer; DEPLOYER_SECRET="$SECRET_EXAMPLE_DEPLOYER"; ECHO_CLIENT=echo-provider; ECHO_SECRET="$SECRET_ECHO_PROVIDER"
  else
    ISSUER="http://localhost:$PORT_IDP"; PLATFORM_AUDIENCE=midgard-core; CAPABILITY_AUDIENCE=platform.example; ECHO_AUDIENCE=example.echo
    OP_SUBJECTS=operator-1; PUB_SUBJECTS='publisher-1=platform.|example.|examples.'
    DEPLOYER_CLIENT=example-deployer; DEPLOYER_SECRET=dev-only-deployer; ECHO_CLIENT=echo-provider; ECHO_SECRET=dev-only-echo-provider
  fi
}

zitadel_up() {
  need "$ZITADEL_BIN"
  stop zitadel
  mkdir -p "$LOCAL/zitadel"
  # ZITADEL's own database login is created by its init step using the PostgreSQL admin connection.
  ( export ZITADEL_DATABASE_POSTGRES_HOST="$PGHOST" ZITADEL_DATABASE_POSTGRES_PORT="$PGPORT" ZITADEL_DATABASE_POSTGRES_DATABASE=zitadel \
      ZITADEL_DATABASE_POSTGRES_USER_USERNAME=zitadel ZITADEL_DATABASE_POSTGRES_USER_PASSWORD="$ZITADEL_DB_PASSWORD" ZITADEL_DATABASE_POSTGRES_USER_SSL_MODE=disable \
      ZITADEL_DATABASE_POSTGRES_ADMIN_USERNAME="$PGUSER" ZITADEL_DATABASE_POSTGRES_ADMIN_PASSWORD="$PGPASSWORD" ZITADEL_DATABASE_POSTGRES_ADMIN_SSL_MODE=disable \
      ZITADEL_EXTERNALSECURE=false ZITADEL_EXTERNALDOMAIN=localhost ZITADEL_EXTERNALPORT="$PORT_ZITADEL" ZITADEL_PORT="$PORT_ZITADEL" \
      ZITADEL_FIRSTINSTANCE_ORG_MACHINE_MACHINE_USERNAME=midgard-admin ZITADEL_FIRSTINSTANCE_ORG_MACHINE_MACHINE_NAME=midgard-admin \
      ZITADEL_FIRSTINSTANCE_ORG_MACHINE_PAT_EXPIRATIONDATE=2099-01-01T00:00:00Z ZITADEL_FIRSTINSTANCE_PATPATH="$LOCAL/zitadel/admin.pat" \
      ZITADEL_MACHINE_IDENTIFICATION_HOSTNAME_ENABLED=true ZITADEL_MACHINE_IDENTIFICATION_PRIVATEIP_ENABLED=false ZITADEL_MACHINE_IDENTIFICATION_WEBHOOK_ENABLED=false
    start zitadel "$ZITADEL_BIN" start-from-init --masterkey "$ZITADEL_MASTERKEY" --tlsMode disabled )
  wait_http "http://localhost:$PORT_ZITADEL/debug/ready" 180
  ZITADEL_URL="http://localhost:$PORT_ZITADEL" ZITADEL_PAT_FILE="$LOCAL/zitadel/admin.pat" OUT_DIR="$IDP_DIR" "$ROOT/scripts/zitadel-bootstrap.sh"
}

core_env() {
  export PLATFORM_BIND_ADDR="127.0.0.1:$PORT_CORE" ZITADEL_ISSUER="$ISSUER"
  export PLATFORM_DATABASE_URL="postgres://midgard_app:$MIDGARD_APP_PASSWORD@$PG_HOSTPORT/midgard_core"
  export PLATFORM_MIGRATION_DATABASE_URL="postgres://midgard_owner:$MIDGARD_OWNER_PASSWORD@$PG_HOSTPORT/midgard_core"
  export PLATFORM_AUDIENCE PLATFORM_OPERATOR_SUBJECTS="$OP_SUBJECTS" PLATFORM_PUBLISHER_SUBJECTS="$PUB_SUBJECTS"
  export REGISTRY_ENDPOINT_ALLOWED_HOSTS=localhost REGISTRY_HEALTH_CHECK_INTERVAL_SECONDS=2
}

up() {
  load_env
  for n in echo-provider nats example-capability platform-core dev-idp zitadel; do stop "$n"; done   # never orphan a previous stack
  sleep 1
  log "building binaries"
  (cd "$ROOT" && cargo build -q --bins) && (cd "$ROOT/examples/sample-application" && go build -o "$BIN/sample-application" .)
  log "preparing roles/databases"
  PSQL_ADMIN="psql -v ON_ERROR_STOP=1 -q" "$ROOT/deployments/compose/init/postgres/01-roles-and-databases.sh" >/dev/null

  if [[ "$IDP" == zitadel ]]; then
    zitadel_up
  else
    DEV_IDP_ISSUER="http://localhost:$PORT_IDP" DEV_IDP_CONFIG="$ROOT/deployments/compose/dev-idp.json" DEV_IDP_BIND="127.0.0.1:$PORT_IDP" \
      start dev-idp "$BIN/dev-idp"
    wait_http "http://localhost:$PORT_IDP/.well-known/openid-configuration" 30
  fi
  idp_vars

  ( core_env; "$BIN/platform-core" migrate ) >"$LOCAL/core-migrate.log" 2>&1 || { cat "$LOCAL/core-migrate.log" >&2; die "core migrations failed"; }
  ( CAPABILITY_MIGRATION_DATABASE_URL="postgres://capability_owner:$CAPABILITY_OWNER_PASSWORD@$PG_HOSTPORT/midgard_capability" "$BIN/example-capability" migrate ) >"$LOCAL/cap-migrate.log" 2>&1 || { cat "$LOCAL/cap-migrate.log" >&2; die "capability migrations failed"; }
  (core_env; start platform-core "$BIN/platform-core" serve)
  wait_http "http://localhost:$PORT_CORE/health/ready" 60

  ( export CAPABILITY_BIND_ADDR="127.0.0.1:$PORT_CAP" CAPABILITY_ISSUER="$ISSUER" CAPABILITY_AUDIENCE="$CAPABILITY_AUDIENCE" CAPABILITY_CORE_AUDIENCE="$PLATFORM_AUDIENCE" \
      CAPABILITY_DATABASE_URL="postgres://capability_app:$CAPABILITY_APP_PASSWORD@$PG_HOSTPORT/midgard_capability" \
      PLATFORM_CORE_URL="http://localhost:$PORT_CORE" CAPABILITY_CLIENT_ID="$DEPLOYER_CLIENT" CAPABILITY_CLIENT_SECRET="$DEPLOYER_SECRET" \
      CAPABILITY_SELF_REGISTER=true CAPABILITY_PUBLIC_ENDPOINT="http://localhost:$PORT_CAP"
    start example-capability "$BIN/example-capability" )
  wait_http "http://localhost:$PORT_CAP/health/ready" 60
  [[ "${WITH_V02:-}" == 1 ]] && up_v02
  log "stack is up: core=:$PORT_CORE idp=:$PORT_IDP capability=:$PORT_CAP (logs in .local/)"
}

up_v02() {
  need "$NATS_SERVER_BIN"
  for n in echo-provider nats; do stop "$n"; done
  sleep 1
  log "building the echo fixture"
  (cd "$ROOT/examples/echo" && go build -o "$BIN/echo" .)
  mkdir -p "$LOCAL/nats"
  ( export NATS_STORE_DIR="$LOCAL/nats" NATS_ADMIN_PASSWORD NATS_PROVIDER_PASSWORD NATS_CLIENT_PASSWORD
    start nats "$NATS_SERVER_BIN" -c "$ROOT/deployments/compose/nats/nats.conf" -p "$PORT_NATS" -m 0 )
  wait_port 127.0.0.1 "$PORT_NATS" 30
  sleep 1
  ECHO_NATS_URL="nats://127.0.0.1:$PORT_NATS" ECHO_NATS_ADMIN_PASSWORD="$NATS_ADMIN_PASSWORD" "$BIN/echo" nats-init
  ( export ECHO_BIND_ADDR="127.0.0.1:$PORT_ECHO" ECHO_ISSUER="$ISSUER" ECHO_AUDIENCE ECHO_CORE_AUDIENCE="$PLATFORM_AUDIENCE" ECHO_CORE_URL="http://localhost:$PORT_CORE" \
      ECHO_CLIENT_ID="$ECHO_CLIENT" ECHO_CLIENT_SECRET="$ECHO_SECRET" ECHO_PUBLIC_ENDPOINT="http://localhost:$PORT_ECHO" \
      ECHO_NATS_URL="nats://127.0.0.1:$PORT_NATS" ECHO_NATS_USER=provider ECHO_NATS_PASSWORD="$NATS_PROVIDER_PASSWORD" ECHO_DEBUG=true
    start echo-provider "$BIN/echo" provider )
  wait_http "http://localhost:$PORT_ECHO/health/ready" 30
  log "v0.2 fixture up: nats=:$PORT_NATS echo-provider=:$PORT_ECHO"
}

wait_port() { # wait_port <host> <port> <seconds>
  local i
  for ((i = 0; i < $3; i++)); do (exec 3<>"/dev/tcp/$1/$2") 2>/dev/null && return 0; sleep 1; done
  die "timed out waiting for $1:$2"
}

case "${1:-}" in
  up) up ;;
  down) for n in echo-provider nats example-capability platform-core dev-idp zitadel; do stop "$n"; done; log "stopped" ;;
  restart-core)
    load_env; idp_vars; stop platform-core; sleep 1; (core_env; start platform-core "$BIN/platform-core" serve)
    wait_http "http://localhost:$PORT_CORE/health/ready" 60 ;;
  env)
    cat <<ENV
export PLATFORM_URL=http://localhost:$PORT_CORE IDP_URL=http://localhost:$PORT_IDP
$( if [[ "$IDP" == zitadel ]]; then echo "export IDP_DIR=$IDP_DIR IDP_TOKEN_URL=http://localhost:$PORT_ZITADEL/oauth/v2/token ZITADEL_URL=http://localhost:$PORT_ZITADEL ZITADEL_PAT_FILE=$LOCAL/zitadel/admin.pat OUT_DIR=$IDP_DIR"; else echo "export OPERATOR_CLIENT_SECRET=dev-only-operator PUBLISHER_CLIENT_SECRET=dev-only-publisher"; fi )
export CAPABILITY_URL=http://localhost:$PORT_CAP SAMPLE_APP=$BIN/sample-application CONTRACT_TOOL=$BIN/contract-tool
export PROVIDER_URL=http://localhost:$PORT_ECHO ECHO_BIN=$BIN/echo ECHO_NATS_URL=nats://127.0.0.1:$PORT_NATS
export NATS_CLIENT_PASSWORD=$(grep '^NATS_CLIENT_PASSWORD=' "$LOCAL/env" 2>/dev/null | cut -d= -f2)
ENV
    ;;
  *) echo "usage: $0 up|down|restart-core|env" >&2; exit 2 ;;
esac
